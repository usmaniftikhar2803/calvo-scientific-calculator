const RTL_LANGS = ['ur', 'ar', 'fa', 'ps', 'pa', 'arz', 'afb', 'apc', 'ary', 'acm'];

/* ---------- Language packs (loaded only when needed) ----------
   English is bundled above. Any other language is one small file in /i18n/
   (for example i18n/ur.js) that adds itself to `translations`.
   - A returning visitor whose saved language is not English gets that one pack
     loaded right here, before the app starts, so the first paint is already correct.
   - Picking a language in the menu loads its pack first, then switches.
   - If a pack cannot be loaded (offline and never opened before), the app stays in English. */
const LANG_PACK_DIR = 'i18n/';
const LANG_CODE_RE = /^[a-z]{2,3}$/;
const langPackLoads = {};

function loadLangPack(lang) {
  if (lang === 'en' || translations[lang]) return Promise.resolve();
  if (!LANG_CODE_RE.test(lang)) return Promise.reject(new Error('Unknown language'));
  if (langPackLoads[lang]) return langPackLoads[lang];
  langPackLoads[lang] = new Promise((resolve, reject) => {
    const s = document.createElement('script');
    s.src = LANG_PACK_DIR + lang + '.js';
    s.async = true;
    s.onload = () => (translations[lang] ? resolve() : reject(new Error('Empty language pack')));
    s.onerror = () => { delete langPackLoads[lang]; reject(new Error('Language pack failed to load')); };
    document.head.appendChild(s);
  });
  return langPackLoads[lang];
}

let currentLang = 'en';
try {
  const savedLang = localStorage.getItem('calvo_lang');
  if (savedLang && savedLang !== 'en' && LANG_CODE_RE.test(savedLang)) {
    currentLang = savedLang;
    document.write('<script src="' + LANG_PACK_DIR + savedLang + '.js"><\/script>');
  }
} catch (e) {}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
    || (translations.en && translations.en[key])
    || key;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
}

function updateLanguageModalUI() {
  const list = document.getElementById('languageList');
  if (!list) return;
  list.querySelectorAll('.language-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === currentLang);
  });
}

function setLanguage(lang) {
  if (!LANG_CODE_RE.test(lang)) lang = 'en';
  if (lang !== 'en' && !translations[lang]) {
    loadLangPack(lang).then(() => setLanguage(lang)).catch(() => setLanguage('en'));
    return;
  }
  currentLang = lang;
  try { localStorage.setItem('calvo_lang', lang); } catch (e) {}
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
  applyStaticTranslations();
  updateLanguageModalUI();
  if (typeof onLanguageChange === 'function') onLanguageChange();
}

document.addEventListener('DOMContentLoaded', () => {
  if (currentLang !== 'en' && !translations[currentLang]) {
    // The saved language's pack did not arrive in time: show English now, switch when it loads.
    const wanted = currentLang;
    currentLang = 'en';
    document.documentElement.lang = 'en';
    document.documentElement.dir = 'ltr';
    applyStaticTranslations();
    updateLanguageModalUI();
    loadLangPack(wanted).then(() => setLanguage(wanted)).catch(() => {});
    return;
  }
  document.documentElement.lang = currentLang;
  document.documentElement.dir = RTL_LANGS.includes(currentLang) ? 'rtl' : 'ltr';
  applyStaticTranslations();
  updateLanguageModalUI();
});
