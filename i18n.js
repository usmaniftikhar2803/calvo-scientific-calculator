const RTL_LANGS = ['ur', 'ar'];

let currentLang = 'en';
try {
  const savedLang = localStorage.getItem('calvo_lang');
  if (savedLang && translations[savedLang]) currentLang = savedLang;
} catch (e) {}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
    || (translations.en && translations.en[key])
    || key;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
}

function updateLanguageModalUI() {
  const list = document.getElementById('languageList');
  if (!list) return;
  list.querySelectorAll('.language-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === currentLang);
  });
}

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  try { localStorage.setItem('calvo_lang', lang); } catch (e) {}
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
  applyStaticTranslations();
  updateLanguageModalUI();
  if (typeof onLanguageChange === 'function') onLanguageChange();
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = RTL_LANGS.includes(currentLang) ? 'rtl' : 'ltr';
  applyStaticTranslations();
  updateLanguageModalUI();
});
